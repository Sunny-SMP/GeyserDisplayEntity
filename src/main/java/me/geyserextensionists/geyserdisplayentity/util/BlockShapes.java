package me.geyserextensionists.geyserdisplayentity.util;

import org.geysermc.geyser.level.block.type.BlockState;

import java.io.BufferedReader;
import java.io.IOException;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.concurrent.ConcurrentHashMap;

/**
 * The shape the resource pack's block renderer draws for a Java block state or block item: one box (in pixels, within
 * the block's 0..16 space) and a texture per face, from block_render.tsv (generated by tools/block_renderer/generate.py).
 */
public final class BlockShapes {

    /**
     * @param from    box corner in pixels
     * @param to      opposite box corner in pixels
     * @param faces   texture index per face, in the order north, south, east, west, up, down; -1 draws no face
     * @param translucent whether any face needs blending (stained glass, ice, ...)
     */
    public record Shape(float[] from, float[] to, int[] faces, boolean translucent) {
    }

    private record Rule(List<Map<String, String[]>> alternatives, int shape) {
        // Every listed property must have one of its values, in at least one alternative ("*" has none: always true)
        boolean matches(Map<String, String> properties) {
            for (Map<String, String[]> alternative : alternatives) {
                if (alternative.entrySet().stream().allMatch(entry -> {
                    String value = properties.get(entry.getKey());
                    if (value == null) return false;
                    for (String allowed : entry.getValue()) {
                        if (allowed.equals(value)) return true;
                    }
                    return false;
                })) return true;
            }
            return false;
        }
    }

    private static final Shape NONE = new Shape(new float[0], new float[0], new int[0], false);

    private static final List<Shape> shapes = new ArrayList<>();
    private static final Map<String, List<Rule>> blocks = new HashMap<>();
    private static final Map<String, Integer> items = new HashMap<>();
    private static final Map<Integer, Shape> stateCache = new ConcurrentHashMap<>();

    private BlockShapes() {
    }

    public static void load(ClassLoader classLoader) throws IOException {
        try (InputStream stream = classLoader.getResourceAsStream("block_render.tsv")) {
            if (stream == null) throw new IOException("block_render.tsv is missing from the jar");
            BufferedReader reader = new BufferedReader(new InputStreamReader(stream, StandardCharsets.UTF_8));
            String line;
            while ((line = reader.readLine()) != null) {
                if (line.isEmpty() || line.startsWith("#")) continue;
                String[] cols = line.split("\t", -1);
                switch (cols[0]) {
                    case "shape" -> {
                        float[] from = {Float.parseFloat(cols[2]), Float.parseFloat(cols[3]), Float.parseFloat(cols[4])};
                        float[] to = {Float.parseFloat(cols[5]), Float.parseFloat(cols[6]), Float.parseFloat(cols[7])};
                        int[] faces = new int[6];
                        for (int i = 0; i < 6; i++) faces[i] = Integer.parseInt(cols[8 + i]);
                        shapes.add(new Shape(from, to, faces, (Integer.parseInt(cols[14]) & 1) != 0));
                    }
                    case "variant" -> blocks.computeIfAbsent(cols[1], k -> new ArrayList<>())
                            .add(new Rule(List.of(parseCondition(cols[2], ",")), Integer.parseInt(cols[3])));
                    case "part" -> {
                        List<Map<String, String[]>> alternatives = new ArrayList<>();
                        for (String alternative : cols[2].split("\\|\\|")) alternatives.add(parseCondition(alternative, ","));
                        blocks.computeIfAbsent(cols[1], k -> new ArrayList<>()).add(new Rule(alternatives, Integer.parseInt(cols[3])));
                    }
                    case "item" -> items.put(cols[1], Integer.parseInt(cols[2]));
                    default -> {
                    }
                }
            }
        }
    }

    // "facing=east,half=bottom" or "north=true|false"; "" and "*" match everything
    private static Map<String, String[]> parseCondition(String text, String separator) {
        Map<String, String[]> condition = new HashMap<>();
        if (text.isEmpty() || text.equals("*")) return condition;
        for (String pair : text.split(separator)) {
            int eq = pair.indexOf('=');
            condition.put(pair.substring(0, eq), pair.substring(eq + 1).split("\\|"));
        }
        return condition;
    }

    /**
     * The shape of a Java block state: the first matching variant, or for multipart blocks the first matching part
     * (the post of a fence or wall). Null when the block has no model box (chests, signs, ...).
     */
    public static Shape forState(int javaId) {
        Shape shape = stateCache.computeIfAbsent(javaId, id -> {
            String state = BlockState.of(id).toString();
            int bracket = state.indexOf('[');
            String block = bracket < 0 ? state : state.substring(0, bracket);
            Map<String, String> properties = new HashMap<>();
            if (bracket >= 0) {
                for (String pair : state.substring(bracket + 1, state.length() - 1).split(",")) {
                    int eq = pair.indexOf('=');
                    if (eq > 0) properties.put(pair.substring(0, eq), pair.substring(eq + 1));
                }
            }
            for (Rule rule : blocks.getOrDefault(block, List.of())) {
                if (rule.matches(properties)) return shapes.get(rule.shape());
            }
            return NONE;
        });
        return shape == NONE ? null : shape;
    }

    /**
     * The shape of a block item's model, or null for items that aren't drawn as a block.
     */
    public static Shape forItem(String javaItem) {
        Integer index = items.get(javaItem);
        return index == null ? null : shapes.get(index);
    }
}
